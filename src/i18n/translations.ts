export const translations: Record<Locale, Dict> = { en, fr, ht };

/**
 * Translate a key with optional interpolation.
 * Falls back to English if the key is missing in the current locale.
 */
export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let str = translations[locale]?.[key] ?? translations.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  // Pluralization: if a _plural key exists and count !== 1
  if (params && 'count' in params) {
    const pluralKey = `${key}_plural`;
    const pluralStr = translations[locale]?.[pluralKey] ?? translations.en[pluralKey];
    if (pluralStr && params.count !== 1) {
      str = pluralStr;
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
  }
  return str;
}
